#!/bin/bash
# One generation round for E2-E4: import replies, withdraw failed batches, replay the experiments, export new batches.
export HF_HOME=${HF_HOME:-$HOME/.cache/huggingface} HF_HUB_OFFLINE=${HF_HUB_OFFLINE:-1} PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=src
python - <<'PY'
from pathlib import Path
from kyground.llm.session import supersede, import_outputs
bdir = Path('runs/session/batches')
r = import_outputs(bdir, 'claude-haiku-4-5 (Claude session sub-agent)')
bad = [b for b, v in r['batches_to_redo'].items() if v != 'no output file']
print('stored', r['stored'], 'failed', bad)
if bad:
    supersede(bdir, bad, "incomplete or failed check: remaining requests regenerated by a new sub-agent")
PY
for e in ablation freshness governance; do timeout 3000 python -m kyground run $e --run-id main 2>&1 | grep -E "wait for generation"; done
python -m kyground gen-export 2>&1 | tail -1
timeout 60 python tools/gen_list.py | awk '{n=$4; o=""; for(i=1;i<=n;i+=300){o=o (o==""?"":",") i}; printf "%s:%s:%s:%s ", substr($1,7), $3, $4, o} END {print ""}'
