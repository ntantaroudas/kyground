#!/bin/bash
# One generation round in isolation (protocol deviation D10): import replies, withdraw failed batches, replay all
# experiments, and export the queued requests one per batch, so that each is answered by its own sub-agent.
export HF_HOME=${HF_HOME:-$HOME/.cache/huggingface} HF_HUB_OFFLINE=${HF_HUB_OFFLINE:-1} PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=src
python - <<'PY'
from pathlib import Path
from kyground.llm.session import supersede, import_outputs
bdir = Path('runs/session/batches')
r = import_outputs(bdir, 'claude-haiku-4-5 (Claude session sub-agent)')
bad = [b for b, v in r['batches_to_redo'].items() if v != 'no output file']
print('stored', r['stored'], 'failed', bad)
if bad:
    supersede(bdir, bad, "incomplete or failed check: remaining requests regenerated by a new sub-agent")
PY
for e in accuracy ablation freshness governance; do timeout 3000 python -m kyground run $e --run-id main 2>&1 | grep -E "wait for generation"; done
python - <<'PY'
import json
from pathlib import Path
import tiktoken
from kyground.llm.session import export_queue
from kyground.schema import load_items
clusters = {i.iid: i.cluster for i in load_items(Path('data/benchmark/v1.0/items.jsonl'))}
s = export_queue(Path('runs/session/pending.jsonl'), Path('runs/session/batches'), clusters, seed=20261005,
                 max_chars=45000, max_requests={"answer": 1, "router": 1, "rewrite": 1, "long_system": 1},
                 tokenizer=tiktoken.get_encoding('o200k_base'))
print(json.dumps(s))
PY
timeout 60 python tools/gen_list.py | awk '{n=$4; o=""; for(i=1;i<=n;i+=300){o=o (o==""?"":",") i}; printf "%s:%s:%s:%s ", substr($1,7), $3, $4, o} END {print ""}'
